-- RLS identity mapping: link a Supabase Auth user to public.users.auth_user_id.
create schema if not exists app;
create or replace function app.current_user_id() returns bigint
language sql stable security definer set search_path = public
as $$ select id from users where auth_user_id = auth.uid() limit 1 $$;
create or replace function app.current_role() returns text
language sql stable security definer set search_path = public
as $$ select role from users where id = app.current_user_id() $$;
create or replace function app.is_admin() returns boolean
language sql stable security definer set search_path = public
as $$ select coalesce(app.current_role() in ('platform_admin','federation_admin','cooperative_admin'), false) $$;

