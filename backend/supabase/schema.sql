create table if not exists workers (
  id bigint generated by default as identity primary key,
  user_id bigint not null unique references users(id) on delete cascade,
  cooperative_id bigint references cooperatives(id) on delete set null,
  name varchar(255) not null,
  phone varchar(20) not null,
  email text,
  latitude double precision,
  longitude double precision,
  service_area_km double precision not null default 10,
  verification_status text not null default 'pending' check (verification_status in ('pending','verified','rejected')),
  verification_date timestamptz,
  verification_notes text,
  profile_photo text,
  experience_years integer not null default 0 check (experience_years >= 0),
  current_workload integer not null default 0 check (current_workload >= 0),
  max_workload integer not null default 5 check (max_workload > 0),
  is_available boolean not null default true,
  total_completed_services integer not null default 0 check (total_completed_services >= 0),
  average_rating numeric(3,2) not null default 0 check (average_rating between 0 and 5),
