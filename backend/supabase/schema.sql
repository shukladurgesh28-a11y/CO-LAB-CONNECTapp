where email = 'worker@demo.com'
and not exists (select 1 from availability a where a.worker_id = workers.id and a.day_of_week = days.day_of_week);

-- Enable Supabase Realtime publication for shared workflow tables.
do $$
declare
  table_name text;
begin
  foreach table_name in array array['service_requests','allocations','bookings','payments','notifications','demand_records'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = table_name
    ) then
      execute format('alter publication supabase_realtime add table public.%I', table_name);
    end if;
  end loop;
end $$;
