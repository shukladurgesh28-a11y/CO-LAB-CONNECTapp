create table if not exists service_requests (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references users(id) on delete restrict,
  service_id bigint not null references services(id) on delete restrict,
  cooperative_id bigint references cooperatives(id) on delete set null,
  description text,
  location_address varchar(500),
  location_lat double precision,
  location_lng double precision,
  preferred_date date,
  preferred_time_start time,
  preferred_time_end time,
  urgency varchar(20) not null default 'normal' check (urgency in ('low','normal','medium','high','urgent')),
  special_requirements jsonb,
  status varchar(30) not null default 'pending',
  allocated_worker_id bigint references workers(id) on delete set null,
  allocation_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (preferred_time_end is null or preferred_time_start is null or preferred_time_end > preferred_time_start)
